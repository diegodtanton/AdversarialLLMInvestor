from __future__ import annotations

from pathlib import Path


# ============================================================
# CONFIG
# ============================================================

ROOT = Path(__file__).resolve().parent.parent

SCRIPTS_DIR = ROOT / "scripts"
ENV_PATH = ROOT / ".env"

OUTPUT_PATH = ROOT / "concat.txt"

MAX_TREE_DEPTH = 3

# Show these directories in the tree, but don't descend into them.
COLLAPSED_DIRS = {
    "data",
    "logs",
}

# Completely hide these.
IGNORED_NAMES = {
    ".git",
    ".DS_Store",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".idea",
    ".vscode",
}

# Never concatenate these even if they appear under scripts.
IGNORED_SUFFIXES = {
    ".pyc",
    ".pyo",
    ".pyd",
    ".so",
    ".dll",
    ".dylib",
}

CONCAT_SUFFIXES = {".py", ".html", ".css", ".js"}


def inclusion_note() -> str:
    ignored = ", ".join(sorted(IGNORED_NAMES))
    collapsed = ", ".join(sorted(COLLAPSED_DIRS))
    suffixes = ", ".join(sorted(CONCAT_SUFFIXES))
    return "\n".join(
        [
            "This file is generated by utils/concat.py for LLM context.",
            "",
            "Included in the file dump below:",
            f"  - {ENV_PATH.relative_to(ROOT)} when present (lines containing API_KEY omitted)",
            f"  - scripts/** with extensions: {suffixes}",
            "",
            "Excluded from the dump:",
            f"  - Path segments named: {ignored}",
            f"  - Binary / build suffixes: {', '.join(sorted(IGNORED_SUFFIXES))}",
            "  - Other repo paths (README, tests, utils, data contents, etc.)",
            "",
            "Repository tree below:",
            f"  - Max depth {MAX_TREE_DEPTH}; contents not listed for: {collapsed}",
            f"  - Hidden in tree: {ignored} and names starting with .git",
        ]
    )


# ============================================================
# TREE
# ============================================================

def should_ignore(path: Path) -> bool:
    return path.name in IGNORED_NAMES or path.name.startswith(".git")


def sorted_children(directory: Path) -> list[Path]:
    children = [path for path in directory.iterdir() if not should_ignore(path)]

    return sorted(
        children,
        key=lambda path: (not path.is_dir(), path.name.casefold()),
    )


def build_tree(
    directory: Path,
    *,
    depth: int = 0,
    prefix: str = "",
) -> list[str]:
    if depth >= MAX_TREE_DEPTH:
        return []

    children = sorted_children(directory)
    lines: list[str] = []

    for index, path in enumerate(children):
        is_last = index == len(children) - 1
        branch = "└── " if is_last else "├── "
        display_name = f"{path.name}/" if path.is_dir() else path.name
        lines.append(f"{prefix}{branch}{display_name}")

        if not path.is_dir():
            continue
        if path.name in COLLAPSED_DIRS:
            continue

        child_prefix = prefix + ("    " if is_last else "│   ")
        lines.extend(build_tree(path, depth=depth + 1, prefix=child_prefix))

    return lines


def repo_tree() -> str:
    return "\n".join([f"{ROOT.name}/", *build_tree(ROOT)])


# ============================================================
# FILE CONCATENATION
# ============================================================

def _path_allowed(path: Path) -> bool:
    if any(part in IGNORED_NAMES for part in path.parts):
        return False
    if path.suffix.lower() in IGNORED_SUFFIXES:
        return False
    return path.suffix.lower() in CONCAT_SUFFIXES


def concat_files() -> list[Path]:
    files: list[Path] = []
    if ENV_PATH.is_file():
        files.append(ENV_PATH)

    for path in SCRIPTS_DIR.rglob("*"):
        if path.is_file() and _path_allowed(path):
            files.append(path)

    return sorted(files, key=lambda path: str(path.relative_to(ROOT)).casefold())


def read_concat_content(path: Path) -> str | None:
    try:
        content = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        print(f"Skipping non-text file: {path.relative_to(ROOT)}")
        return None

    if path == ENV_PATH:
        content = "\n".join(line for line in content.splitlines() if "API_KEY" not in line)

    return content.rstrip()


def concatenate_files() -> str:
    sections: list[str] = []

    for path in concat_files():
        relative_path = path.relative_to(ROOT)
        content = read_concat_content(path)
        if content is None:
            continue

        section = "\n".join(
            [
                "=" * 80,
                f"FILE: {relative_path}",
                "=" * 80,
                "",
                content,
                "",
            ]
        )
        sections.append(section)

    return "\n".join(sections)


# ============================================================
# OUTPUT
# ============================================================

def build_output() -> str:
    return "\n".join(
        [
            "=" * 80,
            "REPO CONCAT: WHAT IS IN THIS FILE",
            "=" * 80,
            "",
            inclusion_note(),
            "",
            "",
            "=" * 80,
            "REPOSITORY TREE",
            "=" * 80,
            "",
            repo_tree(),
            "",
            "",
            "=" * 80,
            "SOURCE FILES",
            "=" * 80,
            "",
            concatenate_files(),
            "",
        ]
    )


def main() -> None:
    output = build_output()
    OUTPUT_PATH.write_text(output, encoding="utf-8")
    files = concat_files()
    print(f"Wrote {OUTPUT_PATH}")
    print(f"Concatenated {len(files)} files.")


if __name__ == "__main__":
    main()
